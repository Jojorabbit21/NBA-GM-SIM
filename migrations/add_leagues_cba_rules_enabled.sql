-- ============================================================
-- leagues.cba_rules_enabled — 멀티플레이어 세션(리그) 단위 CBA 규정 토글
--
-- 배경: 멀티플레이어 FA 화면은 지금 선수를 영입하면 즉시 로스터에 추가된다(협상 없음).
-- 앞으로 실제 연봉 협상 화면을 만들 계획인데, 이건 이 리그가 "샐러리캡 + CBA 규정을
-- 실제로 쓰기로 한" 세션일 때만 의미가 있다 — 룰 없이 그냥 즉시 사인하는 캐주얼 모드도
-- 계속 지원해야 하므로, 리그 생성/설정 시점에 껐다 켰다 할 수 있는 스위치가 필요하다.
--
-- 기존 leagues.cap_enabled(마스터 스위치)와는 별개 축이다 — cap_enabled는 "페이롤을 캡
-- 금액과 비교해서 넘으면 막을 것인가"(숫자 임계값 집행)이고, cba_rules_enabled는 그보다
-- 넓은 개념(버드권한 단계/RFA-QO/루키스케일 구조/협상 화면 자체를 쓸지)이다. 둘 다 켜져
-- 있어야 온전한 CBA 시뮬레이션이 되지만, 독립적으로 끌 수 있어야 한다(예: 캡 금액 집행은
-- 원해도 복잡한 협상 UI는 원치 않는 리그도 있을 수 있음).
--
-- 이번 커밋 시점엔 값을 저장만 한다 — 실제로 FA 협상 화면을 이 값으로 분기하는 로직은
-- 아직 없음(다음 단계에서 views/multi/season/MultiFreeAgentView.tsx 등에 연결 예정).
-- ============================================================

ALTER TABLE public.leagues
    ADD COLUMN IF NOT EXISTS cba_rules_enabled boolean NOT NULL DEFAULT false;

